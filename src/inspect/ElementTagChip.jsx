/** 选区标签芯片。缩略、展开、听写共用，避免缩略态退化成纯文本 */
export default function ElementTagChip({ label, summary, className, n, armed = false, onPress }) {
  return (
    <span
      data-element-tag=""
      data-tag-n={n == null ? undefined : String(n)}
      title={summary || undefined}
      onPointerDown={
        onPress
          ? (e) => {
              if (e.button !== 0) return
              // 点在芯片上，不把这次按下交给输入框的短按展开
              e.preventDefault()
              e.stopPropagation()
              onPress()
            }
          : undefined
      }
      className={cn(
        'inline-flex shrink-0 items-center gap-[3px] bg-transparent',
        // 删除态文字和图标变红，背景保持透明，不铺红底
        armed ? 'text-[#ff3b30]' : 'text-[#2f7fff]',
        onPress && 'pointer-events-auto',
        className,
      )}
    >
      {armed ? <ElementTagDismissIcon /> : <ElementTagIcon />}
      <span>{label}</span>
    </span>
  )
}
